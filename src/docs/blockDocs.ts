/**
 * SPLICE Docs — reference material for every block. Port names, types and defaults are NOT written
 * here: the reference reads them from the registry, so they can never drift from the runtime.
 * What lives here is the explanation. A coverage test fails if any block, port or flow output
 * lacks a description.
 */

export interface BlockDoc {
  /** One sentence. */
  summary: string;
  /** What it does, precisely. */
  details: string;
  /** When it runs (events) or when it is evaluated (reporters) or what triggers it (stack blocks). */
  when: string;
  /** Execution behaviour: same tick or later, what flow it takes, ordering. */
  behavior: string;
  /** What else changes in the world or your state. 'None.' when pure. */
  sideEffects: string;
  /** Equivalent Exchange price, or 'Free.' */
  cost: string;
  /** Inputs, outputs, parameters and flow outputs, by id. */
  ports: Record<string, string>;
  mistakes: string[];
  limitations: string;
  /** How it differs from the block-based tools people may know. */
  scratchDiff?: string;
  related?: string[];
}

